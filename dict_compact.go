var compactRFCMap [8192]int16

func init() {
	initCompactRFCMap()
}

func initCompactRFCMap() {
	for i := range compactRFCMap {
		compactRFCMap[i] = -1
	}
	for i := 0; i < kNumCompactRFCPairs; i++ {
		p := kCompactRFCPairs[i]
		key := (uint32(p.wordID)*0x1E35A7BD ^ uint32(p.transID)*0x85EBCA6B) & 8191
		for {
			if compactRFCMap[key] == -1 {
				compactRFCMap[key] = int16(i)
				break
			}
			key = (key + 1) & 8191
		}
	}
}

func lookupCompactRFCPair(wordID uint16, transID uint8) int {
	key := (uint32(wordID)*0x1E35A7BD ^ uint32(transID)*0x85EBCA6B) & 8191
	for {
		idx := compactRFCMap[key]
		if idx == -1 {
			return -1
		}
		p := kCompactRFCPairs[idx]
		if p.wordID == wordID && p.transID == transID {
			return int(idx)
		}
		key = (key + 1) & 8191
	}
}
