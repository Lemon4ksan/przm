package przm

import (
	"encoding/binary"
	"errors"
	"io"
)

// SymplecticWriter wraps an io.Writer to apply the Symplectic Involution Transform
// to a stream of data in chunks, allowing it to act as a pre-conditioner for
// downstream compressors like Zstandard.
type SymplecticWriter struct {
	w       io.Writer
	chunk   []byte
	pending int
}

func NewSymplecticWriter(w io.Writer) *SymplecticWriter {
	return &SymplecticWriter{
		w:     w,
		chunk: make([]byte, 65536), // 64KB chunks
	}
}

func (sw *SymplecticWriter) Write(p []byte) (n int, err error) {
	for len(p) > 0 {
		avail := len(sw.chunk) - sw.pending
		if len(p) >= avail {
			copy(sw.chunk[sw.pending:], p[:avail])
			sw.pending += avail
			if err := sw.flush(); err != nil {
				return n, err
			}
			p = p[avail:]
			n += avail
		} else {
			copy(sw.chunk[sw.pending:], p)
			sw.pending += len(p)
			n += len(p)
			break
		}
	}
	return n, nil
}

func (sw *SymplecticWriter) flush() error {
	if sw.pending == 0 {
		return nil
	}
	// CompressSymplectic automatically estimates optimal shear and returns a self-describing block
	encoded := CompressSymplectic(sw.chunk[:sw.pending])
	
	// We need to write a 4-byte length prefix for the encoded block so the reader knows how much to read
	var lenBuf [4]byte
	binary.LittleEndian.PutUint32(lenBuf[:], uint32(len(encoded)))
	if _, err := sw.w.Write(lenBuf[:]); err != nil {
		return err
	}
	
	if _, err := sw.w.Write(encoded); err != nil {
		return err
	}
	sw.pending = 0
	return nil
}

func (sw *SymplecticWriter) Close() error {
	if err := sw.flush(); err != nil {
		return err
	}
	if c, ok := sw.w.(io.Closer); ok {
		return c.Close()
	}
	return nil
}

// SymplecticReader wraps an io.Reader to decode a stream generated by SymplecticWriter.
type SymplecticReader struct {
	r       io.Reader
	decoded []byte
	offset  int
	readBuf []byte
}

func NewSymplecticReader(r io.Reader) *SymplecticReader {
	return &SymplecticReader{
		r: r,
	}
}

func (sr *SymplecticReader) Read(p []byte) (n int, err error) {
	if sr.offset < len(sr.decoded) {
		copied := copy(p, sr.decoded[sr.offset:])
		sr.offset += copied
		return copied, nil
	}

	// Read next chunk length
	var lenBuf [4]byte
	if _, err := io.ReadFull(sr.r, lenBuf[:]); err != nil {
		return 0, err
	}
	
	chunkLen := int(binary.LittleEndian.Uint32(lenBuf[:]))
	if chunkLen > 1024*1024 { // Sanity check 1MB max block size
		return 0, errors.New("przm: invalid symplectic chunk length")
	}
	
	if cap(sr.readBuf) < chunkLen {
		sr.readBuf = make([]byte, chunkLen)
	}
	sr.readBuf = sr.readBuf[:chunkLen]
	
	if _, err := io.ReadFull(sr.r, sr.readBuf); err != nil {
		return 0, err
	}
	
	dec, err := DecompressSymplectic(sr.readBuf, nil)
	if err != nil {
		return 0, err
	}
	
	sr.decoded = dec
	sr.offset = 0
	
	copied := copy(p, sr.decoded[sr.offset:])
	sr.offset += copied
	return copied, nil
}
